      <h2>Method</h2>
      <ol class="method"><li><p>Autolyse the flour and water for 90 minutes rather than 60. Wholemeal absorbs water slowly and the bran needs time to soften, and skipping this is why wholemeal doughs feel stiff at mix and slack an hour later.</p></li><li><p>Add the starter, then the salt, squeezing each through.</p></li><li><p>Bulk at 24&deg;C for about three hours with three sets of folds at 30, 60 and 90 minutes. Wholemeal ferments faster than white &mdash; there is more food for the yeast in the bran and germ &mdash; so watch it rather than the clock.</p></li><li><p>Look for a 40&ndash;50% rise, not the 50&ndash;70% you might take a white dough to. Over-fermented wholemeal collapses with very little warning.</p></li><li><p>Pre-shape, rest 15 minutes, shape gently. This dough will not build tension the way a white dough does; forcing it just tears the gluten that the bran has already cut.</p></li><li><p>Seam-up in a well-floured banneton, cover, and refrigerate 12 hours.</p></li><li><p>Bake in a preheated Dutch oven at 240&deg;C fan / 260&deg;C conventional / 480&deg;F: 22 minutes lid on, then 24&ndash;26 minutes lid off at 220&deg;C fan.</p></li><li><p>Internal temperature 96&ndash;99&deg;C / 205&ndash;210&deg;F. The crust will be darker than a white loaf at the same temperature because the extra sugars in wholemeal brown faster.</p></li><li><p>Cool at least three hours. Wholemeal genuinely needs longer than white before it is cuttable.</p></li></ol>
