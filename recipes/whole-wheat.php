      <h2>Why bran makes a wetter dough that rises less</h2>
      <p>Bran particles are sharp at a microscopic scale and they physically cut through developing gluten strands. A 100% wholemeal dough can never build the same gas-holding network as a white one, which is why the loaf is denser however good your technique is.</p><p>Bran is also thirsty: it absorbs several times its own weight in water. That is why 85% hydration here feels like 70% in a white dough, and why a wholemeal loaf made at white-flour hydration comes out dry and tight.</p><p>The practical consequences are a longer autolyse, a shorter bulk, gentler shaping and an earlier bake. Four changes, all of them following from the same fact about bran.</p>
    </div>
  </section>

