      <h2>Method</h2>
      <ol class="method"><li><p>Mix everything at once, including the oil and salt. Focaccia does not need an autolyse; the oil interferes with gluten development anyway and the dough is not trying to be strong.</p></li><li><p>Bulk at 24&deg;C for four hours with four sets of coil folds in the first two. Use a wet hand, not a floured one.</p></li><li><p>Oil a 30 &times; 40 cm tray generously &mdash; more than feels right, about three tablespoons. Tip the dough in and fold it over itself twice.</p></li><li><p>Cover and refrigerate 12&ndash;18 hours.</p></li><li><p>Take it out and leave it at room temperature for two hours. It needs to be properly warm and puffy before it goes in; a cold focaccia dough will not spring.</p></li><li><p>Heat the oven to 240&deg;C fan / 260&deg;C conventional / 480&deg;F. Pour another two tablespoons of oil over the dough and dimple it firmly with oiled fingertips, pushing right down to the tray.</p></li><li><p>Scatter rosemary and flaky salt. Bake 22&ndash;25 minutes until the top is deep gold and the underside is crisp when you lift a corner.</p></li><li><p>Lift it straight out of the tray onto a rack. Left in, the base steams and goes soft within five minutes.</p></li></ol>
