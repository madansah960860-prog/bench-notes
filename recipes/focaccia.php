    <div class="sheet">
      <h2>Why oil is not hydration</h2>
      <p>Hydration in baker's percentage means water as a proportion of flour, and oil is deliberately excluded. Water hydrates starch and lets gluten proteins link; oil does the opposite, coating the proteins and shortening the gluten network.</p><p>That shortening is exactly what you want in focaccia. It gives the tender, slightly crumbly bite that distinguishes it from a chewy bread crumb, and it is why this dough never needs to be strong.</p><p>It also means you can add oil fairly freely without making the dough wetter in any structural sense. The 85% here is still 85%, and the 7% oil is a separate lever.</p>
    </div>
