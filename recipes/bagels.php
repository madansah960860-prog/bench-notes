      <h2>Method</h2>
      <ol class="method"><li><p>Mix everything together. It will look impossibly dry for the first five minutes. Keep going; it hydrates.</p></li><li><p>Knead for 10&ndash;12 minutes by hand or 8 in a mixer on low. This dough genuinely needs kneading &mdash; stretch-and-folds do not develop a 55% dough, because there is not enough water for the gluten to move.</p></li><li><p>Bulk at 22&deg;C for about three hours. It will barely look like it has risen. It has.</p></li><li><p>Divide into twelve 150 g pieces. Roll each into a rope about 20 cm long, wrap it around your palm, and roll the join on the bench to seal.</p></li><li><p>Lay them on oiled parchment, cover, and refrigerate 12&ndash;16 hours.</p></li><li><p>Next day, heat the oven to 230&deg;C fan / 250&deg;C conventional / 450&deg;F and bring a wide pan of water to a rolling boil with a tablespoon of malt syrup or bicarbonate of soda in it.</p></li><li><p>Test one bagel: it should float within ten seconds. If it sinks, give the rest another 30 minutes at room temperature.</p></li><li><p>Boil in batches of three, 45 seconds a side. Longer gives a thicker, chewier crust; much longer gives a wrinkled one.</p></li><li><p>Straight from the water into seeds, then onto a tray. Bake 22&ndash;25 minutes until deep brown. They should sound hollow and read 96&deg;C / 205&deg;F.</p></li></ol>
