      <h2>What the boil actually does</h2>
      <p>Thirty to ninety seconds in boiling water gelatinises the starch on the outside of the bagel, forming a skin that sets before the oven can inflate it. That restraint is what makes a bagel dense and chewy rather than light and open.</p><p>The malt or alkali in the water does two more things: it raises the pH of the surface, which accelerates the Maillard reaction and gives the deep mahogany colour, and the sugar caramelises for gloss. Boiling in plain water gives you a pale, matte bagel that tastes flat.</p><p>The 55% hydration matters for the same reason. A wetter dough would puff in the oven despite the skin, and you would have a boiled bread roll.</p>
    </div>
