      <h2>Method</h2>
      <ol class="method"><li><p>Mix the flour and water only, until no dry flour remains. Cover and leave for an hour. This autolyse hydrates the flour and starts gluten developing without any work from you.</p></li><li><p>Add the starter and squeeze it through the dough, then add the salt and squeeze again. It will feel like it is coming apart. It always does, and it comes back together within ten minutes.</p></li><li><p>Bulk ferment at 24&deg;C for about four hours, with four sets of stretch-and-folds at 30, 60, 90 and 120 minutes. After the last fold, leave it alone.</p></li><li><p>The bulk is done when the dough has risen by roughly 50%, is domed, jiggles as one mass, and has bubbles at the edges where it meets the tub. Judge it by that, never by the clock &mdash; four hours at 24&deg;C is six at 19&deg;C.</p></li><li><p>Turn out, pre-shape into a loose round, and rest 20 minutes uncovered. Then shape tightly and place seam-up in a floured banneton.</p></li><li><p>Cover and refrigerate for 12&ndash;16 hours. The cold retard is what gives the flavour and, more usefully, what lets you bake at seven in the morning without getting up at four.</p></li><li><p>Heat the oven with a Dutch oven inside to 250&deg;C fan / 270&deg;C conventional / 500&deg;F for a full 45 minutes. A hot oven is not the same as a hot pot.</p></li><li><p>Turn the cold loaf onto parchment, score once, decisively, about 1 cm deep at a shallow angle. Lower it in, lid on.</p></li><li><p>Bake 20 minutes with the lid on, then 22&ndash;25 minutes with the lid off at 230&deg;C fan. It is done at an internal temperature of 96&ndash;99&deg;C / 205&ndash;210&deg;F.</p></li><li><p>Cool on a rack for at least two hours before cutting. Cutting a hot loaf gives you a gummy crumb, and that is the loaf's fault less often than it is the baker's impatience.</p></li></ol>
