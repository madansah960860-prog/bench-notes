    <div class="sheet">
      <h2>Why the hydration on the tin is not your hydration</h2>
      <p>A starter is flour and water. A 100%-hydration starter is half flour and half water by weight, so 160 g of starter brings 80 g of flour and 80 g of water into the dough that the simple formula does not count.</p><p>This is why two bakers can both say “75% hydration” and produce visibly different doughs. At 20% starter the difference is around two and a half percentage points; at 40% it is over five, which is the difference between a dough you can shape and one that spreads.</p><p>Every formula on this site publishes both numbers, and if you are comparing with a recipe elsewhere, check whether its starter is counted before you decide your flour is at fault.</p>
