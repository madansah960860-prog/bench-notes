      <h2>Method</h2>
      <ol class="method"><li><p>Heat the oven to 180&deg;C fan / 200&deg;C conventional / 400&deg;F.</p></li><li><p>Mix everything into a stiff, slightly tacky dough. Discard straight from the fridge is fine and there is no need to bring it to room temperature.</p></li><li><p>Split the dough in two. Roll each half between two sheets of parchment as thin as you physically can &mdash; 1&ndash;2 mm. Thickness is the only variable that matters here and almost everybody stops too early.</p></li><li><p>Peel off the top sheet. Score into squares or rectangles with a pizza wheel, prick each one with a fork, and scatter flaky salt over the top.</p></li><li><p>Slide the parchment onto a baking sheet and bake 16&ndash;20 minutes until evenly browned. Watch the edges from minute 14; thin edges catch quickly.</p></li><li><p>Cool completely on the tray. They crisp as they cool, so a cracker that feels slightly soft coming out is usually right.</p></li><li><p>Break along the scores and store airtight.</p></li></ol>
