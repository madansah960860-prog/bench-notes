    <div class="sheet">
      <h2>Why discard works here and not in bread</h2>
      <p>Unfed discard is acidic and has almost no leavening power left. In a loaf that is a problem: you would get a dense, sour brick. In a cracker it is irrelevant, because a cracker is not supposed to rise at all.</p><p>The acidity is actively useful. It weakens gluten, which makes the dough easier to roll extremely thin and gives a snappier, shorter bite. The lactic and acetic acids also give a flavour you cannot get from a plain flour-and-water cracker.</p><p>This is the one recipe where older, sharper discard is better than fresh. A week in the fridge improves it.</p>
    </div>
  </section>

