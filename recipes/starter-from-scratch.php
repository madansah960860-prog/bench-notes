      <h2>Method</h2>
      <ol class="method"><li><p>Day 1: mix 50 g wholemeal flour with 50 g water at about 28&deg;C in a clean jar. Cover loosely. Leave at room temperature for 24 hours.</p></li><li><p>Days 2 and 3: discard all but 50 g, then feed 50 g wholemeal and 50 g water. Once a day.</p></li><li><p>Day 3 or 4 you will very likely see vigorous bubbling and a rise. This is not the yeast you want &mdash; see the note below. Keep going and expect it to stop.</p></li><li><p>Days 4 to 7: switch to white flour, or half white and half wholemeal. Feed once a day, discarding down to 50 g each time. It will smell sharp, then of nothing much, and it will look dead. It is not.</p></li><li><p>Days 8 to 12: move to twice-daily feeding as activity returns. It should start rising predictably a few hours after each feed.</p></li><li><p>Day 12 to 14: it is ready when it reliably doubles within 6&ndash;8 hours of feeding, smells of yoghurt and apples rather than acetone or drains, and passes the float test &mdash; a teaspoon dropped into water should float.</p></li><li><p>To keep it: feed 1:1:1 once a day at room temperature, or move it to the fridge and feed weekly. From cold it needs two feeds at room temperature to come back before you bake.</p></li></ol>
