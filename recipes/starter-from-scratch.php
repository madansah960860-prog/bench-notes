      <h2>The day-three false start, and why everybody is fooled</h2>
      <p>Almost every new starter erupts around day three and then goes completely flat. People assume they killed it. They did not.</p><p>That first burst is mostly <em>Leuconostoc</em> and other bacteria that thrive briefly on the flour's initial conditions and produce a lot of gas. As they acidify the mixture they make it uninhabitable for themselves, the culture crashes, and there is a genuinely dead-looking stretch from about day four to day seven.</p><p>What follows is the culture you actually want: acid-tolerant lactobacilli and wild yeasts, mostly <em>Kazachstania humilis</em>, which take over slowly and establish a stable community by around day ten. The disappointing week in the middle is the process working, not failing, and the single most common reason people give up is not knowing that.</p>
    </div>
  </section>

