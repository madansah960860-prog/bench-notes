          <h2>Why the starter has to be counted</h2>
          <p>A starter is flour and water. A 100%-hydration starter is half of
            each, so 200 g of starter quietly adds 100 g of flour and 100 g of
            water to a dough that your formula has not accounted for.</p>
          <p>At 20% starter that shifts a nominal 75% dough to about 77%. At
            40% it is over 80%. That is the difference between a dough that
            holds a shape and one that spreads across the bench, and it is the
            most common reason two people following the same recipe get
            different results.</p>
        </div>
        <div class="prose">
          <h2>What this site assumes</h2>
          <p>That you have a set of digital scales that read to 1 g, a
            thermometer, and a starter you feed at 100% hydration. Nothing else
            is required &mdash; there is no banneton on this site that could not
            be a bowl and a tea towel, and no Dutch oven that could not be a
            deep tray and a roasting tin on top.</p>
          <p>It also assumes you would rather be told the dough is ready when it
            has risen by half and jiggles as one mass than be told to wait four
            hours. Times are given, but every one of them is followed by the
            thing to actually look for.</p>
          <p>Every fermentation time on this site assumes a dough at 24&deg;C
            after mixing. At 19&deg;C the same dough takes about half as long
            again; at 28&deg;C it is ready in roughly two-thirds of the time.
            That single number explains most of the difference between a recipe
            working in August and failing in January.</p>
        </div>
