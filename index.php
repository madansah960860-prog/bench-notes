      <h2>What baker&rsquo;s percentage actually is</h2>
      <p>Every ingredient is expressed as a percentage of the total flour
        weight, and the flour is always 100%. So a 75% hydration dough has 750 g
        of water for every 1,000 g of flour, and 2% salt means 20 g.</p>
      <p>The percentages always add up to more than 100, which confuses
        everybody at first and is correct. The number is not a share of the
        whole; it is a ratio to the flour.</p>
      <p>The reason it is worth learning is that it makes every formula
        scalable and comparable. You can tell at a glance that a 55% dough will
        be stiff and a 85% dough will be slack, whatever the batch size, and you
        can halve any recipe on this site by halving one number and
        recalculating the rest.</p>
      <p>There are two calculations worth knowing. Scaling up is obvious once
        you see it: multiply the flour and recalculate everything from the
        percentages. Working backwards from a target dough weight is the one
        almost nobody is taught, and it is the more useful of the two &mdash;
        add the percentages together, divide your target weight by that total,
        multiply by a hundred, and you have your flour.</p>
      <p>Both are worked through with real numbers, including how to fill a
        specific tin, on the baker&rsquo;s math page.</p>
      <p><a class="btn" href="pages/categories.php">The maths, worked through</a></p>
    </div>
