          <h2>Who writes it</h2>
          <p>Joss Aldridge baked professionally for seven years, four of them at
            a wholesale bakery in Cambridge producing about 600 loaves a night,
            and now bakes at home and writes this. The professional background
            is why the site is organised around formulas: in a bakery nobody
            writes recipes, because nothing is ever made in the same quantity
            twice.</p>
          <p>The site is called Bench Notes because that is what the notebook on
            the bench actually was &mdash; a column of flour weights, a column
            of dough temperatures, and a note about what happened.</p>

          <h2>Why percentages and not recipes</h2>
          <p>A recipe tells you how to make one specific quantity of one
            specific thing. A formula tells you the relationships, which means
            you can make any quantity, compare two doughs meaningfully, and
            work out what to change when something goes wrong.</p>
          <p>It takes about twenty minutes to learn and it is the single
            highest-value thing a home baker can do. The
            <a href="categories.php">baker&rsquo;s math page</a> works it
            through with real numbers.</p>

          <h2>How the formulas are tested</h2>
          <p>Each is baked at least six times, across at least two seasons, and
            at least twice by somebody else working only from the published
            page. The seasonal spread matters more here than on any other kind
            of recipe site: a formula that only works in a warm kitchen is not
            finished.</p>
          <p>Dough temperature is recorded at every bake and the published
            fermentation times all assume 24&deg;C, which is stated on every
            page rather than left as an unspoken assumption.</p>
        </div>
        <div class="prose">
          <h2>What this site will not do</h2>
          <p>Claim that sourdough is healthier than other bread in any specific,
            measurable way. Long fermentation does reduce some FODMAPs and does
            lower the glycaemic response a little, and both of those effects are
            smaller and less reliable than the internet suggests. Sourdough is
            <strong>not safe for coeliac disease</strong> at any fermentation
            length, and that appears on every formula on this site.</p>
          <p>It will also not sell you a banneton, a lame, a Dutch oven or a
            starter. Every one of those has a kitchen-drawer substitute named in
            the relevant formula.</p>

          <h2>The kitchen</h2>
          <p>A domestic fan oven that reads 12&deg;C low and is corrected with
            an oven thermometer, a cast iron combo cooker, digital scales that
            read to 1 g, and a probe thermometer. Nothing else. There is no
            proofer, no mixer used for anything except the bagels, and no
            temperature-controlled anything.</p>

          <h2>Money</h2>
          <p>Display advertising only. No affiliate links, no sponsored posts,
            no flour or equipment partnerships. A mill and two equipment brands
            have asked, and all three were declined; the detail is on the
            <a href="../policies/advertising-disclosure.php">advertising
            disclosure</a> page.</p>

          <h2>Corrections</h2>
          <p>Two so far. The bagel formula originally gave a 60-second boil per
            side and is now 45, after several readers reported a wrinkled crust.
            And the starter page did not originally explain the day-three false
            rise at all, which was a significant omission and is now the whole
            note on that page.</p>
        </div>
