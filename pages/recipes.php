          <h2>The order to learn them in</h2>
          <p>Start with the <a href="../recipes/starter-from-scratch.php">starter</a>,
            obviously, and read the note about day three before you begin so
            that the flat week does not make you throw it away.</p>
          <p>Then the <a href="../recipes/focaccia.php">focaccia</a>, not the
            country loaf. It is 85% hydration but it needs no shaping at all,
            so you learn to read fermentation without also having to learn
            shaping. Almost everybody is taught these in the wrong order.</p>
          <p>Then the <a href="../recipes/country-loaf.php">country loaf</a>,
            which is the shaping lesson, and after that whichever direction
            interests you: <a href="../recipes/whole-wheat.php">wholemeal</a>
            for fermentation control, or
            <a href="../recipes/bagels.php">bagels</a> for the opposite end of
            the hydration range.</p>
          <p>The <a href="../recipes/discard-crackers.php">crackers</a> are not
            a lesson in anything. They exist so the 50 g you throw away every
            day has somewhere to go.</p>
        </div>
        <div class="prose">
          <h2>A note on flour</h2>
          <p>Every formula here was developed with a UK strong white bread flour
            at around 12.5% protein and a stoneground wholemeal at about 13%.
            If your flour is noticeably stronger or weaker the hydration will
            need adjusting, and the direction is simple: stronger flour takes
            more water.</p>
          <p>Change one thing at a time and write it down. The whole point of a
            ledger is that it is a record, and a baker who keeps notes gets
            better considerably faster than one who does not.</p>
          <h2>Reading a formula before you start</h2>
          <p>Each page opens with the table, then the timings, then a
            fermentation timeline showing when each stage happens across a real
            day. The timeline is the part worth looking at first: it tells you
            whether a bake fits your Saturday, which is usually the actual
            question.</p>
          <p>Four of the six use an overnight cold retard, which means the
            active work happens on one day and the bake on the next. That is
            deliberate &mdash; it is the only way a 4am oven becomes a 7am one.</p>

          <h2>What is not here</h2>
          <p>Enriched doughs, rye, laminated pastry and anything involving a
            commercial yeast. All four are worth knowing and none of them is
            this site. Rye in particular behaves so differently that it needs
            its own set of rules rather than a variation on these.</p>
        </div>
