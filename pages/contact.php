          <h2>If a bake went wrong</h2>
          <p>Send four things and we can almost always diagnose it: the
            temperature of your dough right after mixing, the brand and type of
            flour, how long the bulk ran and what the dough looked like at the
            end of it, and a photograph of the cut crumb.</p>
          <p>The crumb photograph is worth more than any description. A dense
            band at the base means under-fermented or under-baked; large ragged
            holes with a gummy texture mean over-fermented; an even tight crumb
            usually means the shaping had no tension in it. Those three account
            for the overwhelming majority of disappointing loaves.</p>

          <h2>Questions about starters</h2>
          <p>Welcome, and please read the
            <a href="../recipes/starter-from-scratch.php">starter page</a>
            first, particularly the note about day three. Roughly half the
            starter questions we receive are from people on day five of a new
            culture who think they have killed it, and they have not.</p>
          <p>If your starter has visible fuzzy mould, or has turned pink or
            orange, throw the entire jar away rather than scraping. That is the
            one starter situation where the answer is not patience.</p>

          <h2>Sending a formula correction</h2>
          <p>If you think a number on a formula is wrong, say which line and
            what you got. Percentages are checkable arithmetic, so this is one
            of the few kinds of correction that can be settled definitively,
            and we would much rather hear it than leave a wrong figure up.</p>
          <p>Both corrections made so far came from readers: the bagel boil
            time and the missing note about the day-three false rise on the
            starter page. Both are recorded on the pages themselves.</p>

          <h2>What we cannot do</h2>
          <p>Advise on coeliac disease or any medical diet, calculate nutrition
            for your version, or confirm a bake is safe for a particular
            allergy. Our figures are estimates and our allergen notes cover the
            formula as written; the reasons are in the
            <a href="../policies/disclaimer.php">disclaimer</a>.</p>
          <p>We do not accept guest posts, sponsored content or link requests,
            and those emails are deleted without a reply.</p>

          <h2>Scaling help</h2>
          <p>If you want a formula scaled to a particular tin, a particular
            number of loaves or a particular bag of flour, send the target and
            we will do the arithmetic and send it back. It takes about a
            minute and it is the most common request this inbox gets.</p>
          <p>It is also worth doing yourself once. The method is on the
            <a href="categories.php">baker&rsquo;s math page</a> and it is two
            lines of arithmetic: add the percentages, divide the target dough
            weight by that total, multiply by a hundred for the flour, then
            take every other line as a percentage of that.</p>
