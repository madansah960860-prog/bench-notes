      <h2>Going the other way: from a dough weight</h2>
      <p>The more useful calculation, and the one almost nobody is taught. You
        have a tin that takes 950 g of dough. How much of everything?</p>
      <p>Add the percentages: 100 + 75 + 20 + 2.2 = <strong>197.2</strong>.
        Divide your target dough weight by that total and multiply by 100 to get
        the flour: 950 &divide; 197.2 &times; 100 = <strong>482 g of
        flour</strong>.</p>
      <p>Then every other line follows from the flour figure. Water is 75% of
        482, so 361 g. Starter is 20%, so 96 g. Salt is 2.2%, so 11 g. Total:
        950 g, which is what you asked for.</p>
      <p>That single calculation is the whole reason bakers use percentages
        rather than recipes, and it works for any formula on this site.</p>
    </div>
  </section>

