          <h2>The three numbers worth memorising</h2>
          <p><strong>Salt, 2%.</strong> Below about 1.8% bread tastes flat and
            ferments too fast; above about 2.4% it tastes salty and fermentation
            slows noticeably. Almost every bread formula in the world sits
            between those two.</p>
          <p><strong>Starter, 20%.</strong> A useful default. Less means a
            longer, cooler ferment and more flavour; more means faster and less
            control. Doubling the starter roughly halves the bulk time.</p>
          <p><strong>Internal temperature, 96&ndash;99&deg;C.</strong> A lean
            loaf is baked when the middle reaches that. Colour is not doneness
            and the hollow-tap test is a folk method that works about as often
            as it does not.</p>
        </div>
        <div class="prose">
          <h2>Temperature is the missing variable</h2>
          <p>Every fermentation time on this site assumes a dough at about
            24&deg;C. A dough at 19&deg;C will take roughly half as long again;
            at 28&deg;C it will be ready in two-thirds of the time.</p>
          <p>This is why a recipe that worked in August fails in January in the
            same kitchen, and why &ldquo;bulk for four hours&rdquo; is
            information about the writer's kitchen rather than about bread. Take
            the temperature of your dough after mixing, write it in the margin
            next to the time, and within about six bakes you will have a
            personal conversion table that is worth more than any recipe.</p>
        </div>
      </div>
